static uint32_t next_cp(const char* t, size_t len, size_t* i) {
    uint8_t c = (uint8_t)t[*i];
    (*i)++;
    if(c < 0x80) return c;
    if((c & 0xE0) == 0xC0 && *i < len) {
        uint8_t c2 = (uint8_t)t[*i];
        if((c2 & 0xC0) == 0x80) {
            (*i)++;
            return ((uint32_t)(c & 0x1F) << 6) | (c2 & 0x3F);
        }
    } else if((c & 0xF0) == 0xE0 && *i + 1 < len) {
        uint8_t c2 = (uint8_t)t[*i];
        uint8_t c3 = (uint8_t)t[*i + 1];
        if((c2 & 0xC0) == 0x80 && (c3 & 0xC0) == 0x80) {
            *i += 2;
            return ((uint32_t)(c & 0x0F) << 12) | ((uint32_t)(c2 & 0x3F) << 6) | (c3 & 0x3F);
        }
    } else if((c & 0xF8) == 0xF0) {
        size_t k = 0;
        while(k < 3 && *i < len && ((uint8_t)t[*i] & 0xC0) == 0x80) {
            (*i)++;
            k++;
        }
    }
    return '?';
}

static const uint8_t* glyph_for(uint32_t cp) {
    if(cp == '\t' || cp == 0xA0) cp = ' ';
    if(cp == 0x2013 || cp == 0x2014) cp = '-';
    if(cp == 0x2018 || cp == 0x2019) cp = '\'';
    if(cp == 0x201C || cp == 0x201D || cp == 0xAB || cp == 0xBB) cp = '"';
    if(cp >= 0x20 && cp <= 0x7E) return FONT_ASCII[cp - 0x20];
    if(cp >= 0x410 && cp <= 0x44F) return FONT_CYR[cp - 0x410];
    if(cp == 0x401) return FONT_CYR[64];
    if(cp == 0x451) return FONT_CYR[65];
    return FONT_ASCII['?' - 0x20];
}

static size_t layout_lines(const char* text, size_t len, uint16_t* ls, size_t max_lines, int cols) {
    size_t n = 0;
    ls[n++] = 0;
    int col = 0;
    size_t i = 0;
    while(i < len && n < max_lines - 1) {
        size_t start = i;
        uint32_t cp = next_cp(text, len, &i);
        if(cp == '\n') {
            col = 0;
            ls[n++] = (uint16_t)i;
            continue;
        }
        if(col == cols) {
            col = 0;
            ls[n++] = (uint16_t)start;
        }
        col++;
    }
    return n;
}

typedef struct {
    FuriMutex* mutex;
    FuriMessageQueue* queue;
    ViewPort* vp;
    Storage* storage;
    char text[TEXT_MAX];
    size_t len;
    uint16_t line_start[LINE_MAX];
    size_t lines;
    int scroll;
    const char* status;
} App;

static void relayout(App* a) {
    a->lines = layout_lines(a->text, a->len, a->line_start, LINE_MAX, COLS);
}

static void load_from_sd(App* a) {
    a->len = 0;
    a->text[0] = 0;
    File* f = storage_file_alloc(a->storage);
    if(storage_file_open(f, SAVE_FILE, FSAM_READ, FSOM_OPEN_EXISTING)) {
        size_t n = storage_file_read(f, a->text, TEXT_MAX - 1);
        storage_file_close(f);
        size_t w = 0;
        for(size_t i = 0; i < n; i++) {
            if(a->text[i] != '\r') a->text[w++] = a->text[i];
        }
        a->len = w;
        a->text[w] = 0;
        a->status = w ? "Loaded" : "File is empty";
    } else {
        a->status = "No received.txt";
    }
    storage_file_free(f);
    a->scroll = 0;
    relayout(a);
}

static void delete_from_sd(App* a) {
    storage_simply_remove(a->storage, SAVE_FILE);
    a->len = 0;
    a->text[0] = 0;
    a->scroll = 0;
    a->status = "Deleted from SD";
    relayout(a);
}

static void draw_glyph(Canvas* canvas, int x, int y, const uint8_t* g) {
    for(int cx = 0; cx < 5; cx++) {
        uint8_t b = g[cx];
        for(int cy = 0; cy < 8; cy++) {
            if(b & (1 << cy)) canvas_draw_dot(canvas, x + cx, y + cy);
        }
    }
}

static void draw_cb(Canvas* canvas, void* ctx) {
    App* a = ctx;
    furi_mutex_acquire(a->mutex, FuriWaitForever);
    canvas_clear(canvas);
    canvas_set_color(canvas, ColorBlack);
    if(a->len == 0) {
        canvas_set_font(canvas, FontSecondary);
        canvas_draw_str(canvas, 2, 10, a->status ? a->status : "No text");
        canvas_draw_str(canvas, 2, 24, "Put received.txt in:");
        canvas_draw_str(canvas, 2, 34, "ext/apps_data/bt_reader");
        canvas_draw_str(canvas, 2, 48, "OK: reload");
        canvas_draw_str(canvas, 2, 58, "Hold OK: delete file");
    } else {
        for(int r = 0; r < ROWS; r++) {
            int li = a->scroll + r;
            if(li >= (int)a->lines) break;
            size_t p = a->line_start[li];
            int col = 0;
            while(p < a->len && col < COLS) {
                uint32_t cp = next_cp(a->text, a->len, &p);
                if(cp == '\n') break;
                draw_glyph(canvas, col * CELL_W, r * CELL_H, glyph_for(cp));
                col++;
            }
        }
        if((int)a->lines > ROWS) {
            int thumb = 64 * ROWS / (int)a->lines;
            if(thumb < 3) thumb = 3;
            int range = (int)a->lines - ROWS;
            int y = (64 - thumb) * a->scroll / range;
            canvas_draw_box(canvas, 126, y, 2, thumb);
        }
    }
    furi_mutex_release(a->mutex);
}

static void input_cb(InputEvent* e, void* ctx) {
    furi_message_queue_put((FuriMessageQueue*)ctx, e, 0);
}

int32_t bt_reader_app(void* p) {
    UNUSED(p);
    App* a = malloc(sizeof(App));
    memset(a, 0, sizeof(App));
    a->mutex = furi_mutex_alloc(FuriMutexTypeNormal);
    a->queue = furi_message_queue_alloc(8, sizeof(InputEvent));
    a->storage = furi_record_open(RECORD_STORAGE);
    storage_simply_mkdir(a->storage, EXT_PATH("apps_data"));
    storage_simply_mkdir(a->storage, SAVE_DIR);
    a->lines = 1;
    load_from_sd(a);

    a->vp = view_port_alloc();
    view_port_draw_callback_set(a->vp, draw_cb, a);
    view_port_input_callback_set(a->vp, input_cb, a->queue);
    Gui* gui = furi_record_open(RECORD_GUI);
    gui_add_view_port(gui, a->vp, GuiLayerFullscreen);

    InputEvent ev;
    bool run = true;
    while(run) {
        if(furi_message_queue_get(a->queue, &ev, FuriWaitForever) != FuriStatusOk) continue;
        furi_mutex_acquire(a->mutex, FuriWaitForever);
        int max_scroll = (int)a->lines - ROWS;
        if(max_scroll < 0) max_scroll = 0;
        if(ev.type == InputTypeShort || ev.type == InputTypeRepeat) {
            if(ev.key == InputKeyUp && a->scroll > 0) a->scroll--;
            if(ev.key == InputKeyDown && a->scroll < max_scroll) a->scroll++;
            if(ev.key == InputKeyLeft) a->scroll = (a->scroll > ROWS) ? a->scroll - ROWS : 0;
            if(ev.key == InputKeyRight)
                a->scroll = (a->scroll + ROWS < max_scroll) ? a->scroll + ROWS : max_scroll;
            if(ev.key == InputKeyOk && ev.type == InputTypeShort) load_from_sd(a);
            if(ev.key == InputKeyBack) run = false;
        } else if(ev.type == InputTypeLong && ev.key == InputKeyOk) {
            delete_from_sd(a);
        }
        furi_mutex_release(a->mutex);
        view_port_update(a->vp);
    }

    gui_remove_view_port(gui, a->vp);
    furi_record_close(RECORD_GUI);
    view_port_free(a->vp);
    furi_record_close(RECORD_STORAGE);
    furi_message_queue_free(a->queue);
    furi_mutex_free(a->mutex);
    free(a);
    return 0;
}
